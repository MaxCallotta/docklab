export function translateBackendMessage(message) {
  if (!message) return message
  for (const [pattern, english] of rules) {
    const match = message.match(pattern)
    if (match) {
      return english.replace(/\$(\d+)/g, (_, index) => match[Number(index)] ?? '')
    }
  }
  return message
}
