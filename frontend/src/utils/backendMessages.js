const rules = []

function addRule(zh, en) {
  const pattern = zh
    .split(/\{[^}]+\}/)
    .map((part) => part.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'))
    .join('(.+?)')
  rules.push([new RegExp(`^${pattern}$`), en])
}

